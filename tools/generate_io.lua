-- File side of tools/generate.lua: loads Ketho's name lists, writes the split manifest, prints the report.
local M = {}

local Docs = require("tools.docs")
local Flavors = require("tools.flavors")
local Home = require("home")
local Serialize = require("serialize")
local fs = require("fs")

local KETHO_FILES = { "GlobalAPI", "Frames", "FrameXML", "WidgetAPI", "Events" }
local DOCS_PATH = "Interface/AddOns/Blizzard_APIDocumentationGenerated"
local HEADER = "-- Generated by tools/generate.lua from Blizzard API docs and Ketho's name lists. Do not edit.\n"
local SHOWN_DUPLICATES = 10
local COUNTED = { "functions", "events", "enums", "constants", "structs", "widgets" }

local function readRequired(path)
  local text = fs.readFile(path)
  if not text then
    error("missing " .. path .. " (run: bash tools/fetch.sh <branch>)", 0)
  end
  return text
end

-- Runs each Ketho file in an empty sandbox and keeps the table it returns.
function M.loadKetho(dir)
  local ketho = {}
  for _, name in ipairs(KETHO_FILES) do
    local fn, err = Docs.compile(readRequired(dir .. "/" .. name .. ".lua"), "@" .. name .. ".lua", {})
    if not fn then
      error(err, 0)
    end
    ketho[name] = fn()
  end
  return ketho
end

local function sortedKeys(t)
  local keys = {}
  for key in pairs(t) do
    keys[#keys + 1] = key
  end
  table.sort(keys)
  return keys
end

local function clearDir(dir)
  if fs.isdir(dir) then
    for _, name in ipairs(fs.list(dir)) do
      os.remove(dir .. "/" .. name)
    end
  end
  fs.mkdirp(dir)
end

-- Writes api/<flavor>/{<File>.lua..., init.lua, globals.lua} under root; returns { [relative path] = bytes }.
function M.writeSplit(root, result)
  local manifest = result.manifest
  local rel = "api/" .. manifest.flavor
  clearDir(root .. "/" .. rel)
  local sizes = {}
  local function write(name, value)
    local text = HEADER .. Serialize.dump(value)
    fs.writeFile(root .. "/" .. rel .. "/" .. name .. ".lua", text)
    sizes[rel .. "/" .. name .. ".lua"] = #text
  end
  local files = sortedKeys(result.files)
  for _, name in ipairs(files) do
    write(name, result.files[name])
  end
  local index = { files = files }
  for _, key in ipairs({ "flavor", "branch", "version", "mirrorCommit" }) do
    index[key] = manifest[key]
  end
  write("init", index)
  write("globals", result.globals)
  return sizes
end

-- Sets api/versions.lua[meta.flavor] = { version, mirrorCommit, kethoCommit }, keeping the other flavors.
function M.updateVersions(root, meta)
  local path = root .. "/api/versions.lua"
  local versions = fs.exists(path) and assert(loadfile(path))() or {}
  versions[meta.flavor] = { version = meta.version, mirrorCommit = meta.mirrorCommit, kethoCommit = meta.kethoCommit }
  fs.mkdirp(root .. "/api")
  fs.writeFile(path, HEADER .. Serialize.dump(versions))
end

local function count(t)
  local n = 0
  for _ in pairs(t) do
    n = n + 1
  end
  return n
end

-- Duplicate keys (count + the first few) and the doc fields the manifest does not carry.
local function printFindings(report)
  local duplicates = report.duplicates
  print(#duplicates .. " duplicate keys (last file wins)")
  for i = 1, math.min(#duplicates, SHOWN_DUPLICATES) do
    print("  " .. duplicates[i])
  end
  local ignored = {}
  for _, name in ipairs(sortedKeys(report.ignoredFields)) do
    ignored[#ignored + 1] = name .. "=" .. report.ignoredFields[name]
  end
  print("ignored doc fields: " .. table.concat(ignored, " "))
  local dropped = {}
  for _, namespace in ipairs(sortedKeys(report.dropped)) do
    dropped[#dropped + 1] = namespace .. "=" .. report.dropped[namespace]
  end
  print("dropped (no function of the namespace in Ketho's GlobalAPI): " .. table.concat(dropped, " "))
end

local function printReport(result, errors, sizes)
  local parts = {}
  for _, section in ipairs(COUNTED) do
    parts[#parts + 1] = section .. "=" .. count(result.manifest[section])
  end
  parts[#parts + 1] = "globals.api=" .. count(result.globals.api)
  print("counts: " .. table.concat(parts, " "))
  local unknown = sortedKeys(result.report.unknownTypes)
  print(#unknown .. " unknown types: " .. table.concat(unknown, ", "))
  printFindings(result.report)
  print(#errors .. " doc load errors")
  for _, e in ipairs(errors) do
    print("  " .. e.file .. ": " .. e.err)
  end
  local largest = sortedKeys(sizes)
  table.sort(largest, function(a, b)
    return sizes[a] > sizes[b]
  end)
  print("largest file: " .. largest[1] .. " (" .. sizes[largest[1]] .. " bytes)")
end

-- The docs loader's findings: unresolved Enum/Constants references (warnings: they load as 0) and its notes.
function M.docsReportLines(report)
  local lines = { #report.unresolved .. " unresolved Enum/Constants references (loaded as 0)" }
  for _, ref in ipairs(report.unresolved) do
    lines[#lines + 1] = "  " .. ref
  end
  for _, note in ipairs(report.notes) do
    lines[#lines + 1] = note
  end
  return lines
end

-- 1 when any doc failed to load or the docs' values did not settle; unresolved references alone do not fail.
function M.exitCode(errors, report)
  return (#errors == 0 and report.settled) and 0 or 1
end

local function kitRoot()
  local source = debug.getinfo(1, "S").source:sub(2):gsub("\\", "/")
  local root = source:gsub("/?tools/generate_io%.lua$", "")
  return root == "" and "." or root
end

local function trim(text)
  return (text:gsub("^%s+", ""):gsub("%s+$", ""))
end

-- Script entry: returns the exit code (see M.exitCode; the manifest is still written).
function M.main(Generate, flavor)
  if not flavor then
    io.stderr:write("usage: python tools/run51.py --script tools/generate.lua <flavor>\n")
    return 2
  end
  local branch = Flavors.get(flavor).branch
  local gethe = Home.path("mirror", "gethe", branch)
  local ketho = Home.path("mirror", "ketho", branch)
  local meta = {
    flavor = flavor,
    branch = branch,
    version = trim(readRequired(gethe .. "/version.txt")),
    mirrorCommit = trim(readRequired(gethe .. "/COMMIT")),
    kethoCommit = trim(readRequired(ketho .. "/COMMIT")),
  }
  local entries, errors, docsReport = Docs.loadDir(gethe .. "/" .. DOCS_PATH)
  local result = Generate.build(entries, M.loadKetho(ketho), meta)
  local root = kitRoot()
  local sizes = M.writeSplit(root, result)
  M.updateVersions(root, meta)
  printReport(result, errors, sizes)
  for _, line in ipairs(M.docsReportLines(docsReport)) do
    print(line)
  end
  return M.exitCode(errors, docsReport)
end

return M
