-- Combat state: the player's regen events and lockdown, and the engaged flags of the actors.
local A = require("assert")
local Actors = require("combat_actors")
local Combat = require("combat")
local H = require("tests.helpers.combat")
local State = require("combat_state")

local function test_engage_fires_regen_once_and_sets_lockdown() -- (G8)
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    local inside = {}
    local log = H.watch(w, { "PLAYER_REGEN_DISABLED", "UNIT_FLAGS" })
    local frame = _G.CreateFrame("Frame")
    frame:RegisterEvent("PLAYER_REGEN_DISABLED")
    frame:SetScript("OnEvent", function()
      inside = { _G.InCombatLockdown(), _G.UnitAffectingCombat("player") }
    end)
    State.engage(w, brute, player)
    A.same(inside, { false, false }) -- lockdown begins after the event fires
    A.same(H.names(log), { "PLAYER_REGEN_DISABLED", "UNIT_FLAGS", "UNIT_FLAGS" })
    A.eq(log[2][3], "player")
    A.eq(_G.InCombatLockdown(), true)
    A.eq(_G.UnitAffectingCombat("player"), true)
    A.eq(_G.UnitAffectingCombat("boss1"), true)
    local count = #log
    State.engage(w, brute, player) -- a second engage adds no event
    A.eq(#log, count)
  end)
end

local function test_combat_drops_after_the_delay_assumed() -- (C10)
  H.withCombat("retail", function(w, c)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    A.eq(c.dropDelay, 5)
    State.engage(w, brute, player)
    local log = H.watch(w, { "PLAYER_REGEN_ENABLED" })
    local lockdown
    local frame = _G.CreateFrame("Frame")
    frame:RegisterEvent("PLAYER_REGEN_ENABLED")
    frame:SetScript("OnEvent", function()
      lockdown = _G.InCombatLockdown()
    end)
    State.disengage(w, brute)
    A.eq(_G.UnitAffectingCombat("boss1"), false)
    w:advance(4.9)
    A.eq(#log, 0)
    A.eq(_G.InCombatLockdown(), true)
    w:advance(0.2)
    A.eq(#log, 1)
    A.eq(lockdown, false) -- lockdown ends before the event fires (G8)
    A.eq(_G.UnitAffectingCombat("player"), false)
  end)
end

local function test_drop_in_reads_the_pending_drop()
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    A.eq(State.dropIn(w), nil)
    State.engage(w, brute, Actors.get(w, "player"))
    State.disengage(w, brute)
    w:advance(3)
    A.truthy(math.abs(State.dropIn(w) - 2) < 1e-9, tostring(State.dropIn(w)))
  end)
end

local function test_restore_drop_resumes_combat_silently_and_drops_it_later()
  H.withCombat("retail", function(w)
    local log = H.watch(w, { "PLAYER_REGEN_DISABLED", "PLAYER_REGEN_ENABLED" })
    local hook
    Combat.listen(w, "lockdown", function(on)
      hook = on
    end)
    State.restoreDrop(w, 1)
    A.same({ _G.InCombatLockdown(), #log, hook }, { true, 0, true })
    w:advance(1)
    A.same({ _G.InCombatLockdown(), H.names(log) }, { false, { "PLAYER_REGEN_ENABLED" } })
  end)
end

local function test_engaging_again_inside_the_delay_cancels_the_drop()
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    State.engage(w, brute, player)
    local log = H.watch(w, { "PLAYER_REGEN_DISABLED", "PLAYER_REGEN_ENABLED" })
    State.disengage(w, brute)
    w:advance(2)
    State.engage(w, brute, player)
    w:advance(10)
    A.eq(#log, 0)
    A.eq(_G.InCombatLockdown(), true)
  end)
end

local function test_a_second_disengage_restarts_the_delay()
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    State.engage(w, brute, player)
    local log = H.watch(w, { "PLAYER_REGEN_ENABLED" })
    State.disengage(w, brute)
    w:advance(2)
    State.engage(w, brute, player)
    State.disengage(w, brute)
    w:advance(4) -- 6s after the first disengage, 4s after the second
    A.eq(#log, 0)
    w:advance(1.1)
    A.eq(#log, 1)
  end)
end

local function test_a_dead_foe_ends_combat_after_the_delay()
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    State.engage(w, brute, player)
    local log = H.watch(w, { "PLAYER_REGEN_ENABLED" })
    Actors.setDead(w, brute, true)
    w:advance(5)
    A.eq(#log, 1)
    A.eq(_G.InCombatLockdown(), false)
  end)
end

local function test_a_second_live_foe_keeps_combat_going()
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    local other = Actors.add(w, { kind = "npc", name = "Imp", hostile = true })
    State.engage(w, brute, player)
    State.engage(w, other, player)
    local log = H.watch(w, { "PLAYER_REGEN_ENABLED" })
    State.disengage(w, brute)
    w:advance(10)
    A.eq(#log, 0)
    Actors.remove(w, other)
    w:advance(5)
    A.eq(#log, 1)
  end)
end

local function test_mock_combat_flag_still_answers()
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    w:setMock({ combat = true })
    A.eq(_G.InCombatLockdown(), true)
    local log = H.watch(w, { "PLAYER_REGEN_DISABLED", "PLAYER_REGEN_ENABLED" })
    State.engage(w, brute, player) -- already in combat: no second PLAYER_REGEN_DISABLED
    State.disengage(w, brute)
    w:advance(5)
    A.same(H.names(log), { "PLAYER_REGEN_ENABLED" })
    A.eq(_G.InCombatLockdown(), false)
  end)
end

local function test_party_member_combat_does_not_fire_player_regen()
  H.withCombat("retail", function(w)
    local ann, brute = H.pair(w)
    ann.inParty = true
    local log = H.watch(w, { "PLAYER_REGEN_DISABLED", "UNIT_FLAGS" })
    State.engage(w, brute, ann)
    A.same(H.names(log), { "UNIT_FLAGS", "UNIT_FLAGS" })
    A.eq(_G.UnitAffectingCombat("party1"), true)
    A.eq(_G.UnitAffectingCombat("boss1"), true)
    A.eq(_G.InCombatLockdown(), false)
    A.eq(_G.UnitAffectingCombat("player"), false)
  end)
end

local function test_engaging_a_friendly_does_not_start_combat()
  H.withCombat("retail", function(w)
    local ann = H.pair(w)
    local player = Actors.get(w, "player")
    local log = H.watch(w, { "PLAYER_REGEN_DISABLED" })
    State.engage(w, ann, player)
    A.eq(#log, 0)
    A.eq(_G.InCombatLockdown(), false)
  end)
end

local function test_a_dead_actor_engages_no_one()
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    Actors.setDead(w, brute, true)
    local log = H.watch(w, { "PLAYER_REGEN_DISABLED" })
    State.engage(w, brute, player)
    A.eq(#log, 0)
    A.eq(_G.InCombatLockdown(), false)
  end)
end

local function test_engage_rejects_a_value_that_is_not_an_actor()
  H.withCombat("retail", function(w)
    local ann = H.pair(w)
    local ok, err = pcall(State.engage, w, ann, { guid = "x" })
    A.eq(ok, false)
    A.contains(err, "not an actor")
  end)
end

local function test_lockdown_hook_follows_the_mock_flag()
  H.withCombat("retail", function(w)
    local _, brute = H.pair(w)
    local player = Actors.get(w, "player")
    local seen = {}
    Combat.listen(w, "lockdown", function(on)
      seen[#seen + 1] = { on, w.mock.combat }
    end)
    State.engage(w, brute, player)
    State.engage(w, brute, player)
    State.disengage(w, brute)
    w:advance(w.combat.dropDelay + 0.1)
    A.same(seen, { { true, true }, { false, false } })
  end)
end

return function()
  test_engage_fires_regen_once_and_sets_lockdown()
  test_combat_drops_after_the_delay_assumed()
  test_drop_in_reads_the_pending_drop()
  test_restore_drop_resumes_combat_silently_and_drops_it_later()
  test_engaging_again_inside_the_delay_cancels_the_drop()
  test_a_second_disengage_restarts_the_delay()
  test_a_dead_foe_ends_combat_after_the_delay()
  test_a_second_live_foe_keeps_combat_going()
  test_mock_combat_flag_still_answers()
  test_party_member_combat_does_not_fire_player_regen()
  test_engaging_a_friendly_does_not_start_combat()
  test_a_dead_actor_engages_no_one()
  test_engage_rejects_a_value_that_is_not_an_actor()
  test_lockdown_hook_follows_the_mock_flag()
end
