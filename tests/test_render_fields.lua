-- Texture and font string fields of a render item: render_fields.lua with render_read.lua.
local A = require("assert")
local H = require("tests.helpers.render")
local Render = require("render")

local FONT = "Fonts\\FRIZQT__.TTF"

-- A texture over a 100x100 frame; fn gets the world, the texture and a function that snapshots and returns
-- the texture's item and the snapshot.
local function withTexture(fn)
  H.withRender(function(w)
    local frame = _G.CreateFrame("Frame", "Host", _G.UIParent)
    frame:SetSize(100, 100)
    frame:SetPoint("CENTER")
    local texture = frame:CreateTexture("Tex")
    texture:SetAllPoints()
    fn(w, texture, function()
      local snap = Render.snapshot(w)
      return H.item(snap, "Tex"), snap
    end)
  end)
end

-- A font string of a 100x100 frame, sized by its text.
local function withFontString(fn)
  H.withRender(function(w)
    local frame = _G.CreateFrame("Frame", "Host", _G.UIParent)
    frame:SetSize(100, 100)
    frame:SetPoint("CENTER")
    local fontString = frame:CreateFontString("Str")
    fontString:SetPoint("CENTER")
    fn(w, fontString, function()
      local snap = Render.snapshot(w)
      return H.item(snap, "Str"), snap
    end)
  end)
end

local function test_texture_file_refs_and_assets()
  withTexture(function(_, texture, read)
    A.eq(read().file, nil)
    A.eq(read().atlas, nil)
    A.eq(read().color, nil)
    texture:SetTexture("Interface\\AddOns\\Demo\\Media\\Missing")
    local item, snap = read()
    A.eq(item.file, "path:interface/addons/demo/media/missing")
    A.same(snap.assets[item.file], { kind = "path", path = "Interface/AddOns/Demo/Media/Missing" })
    texture:SetTexture(136235)
    item, snap = read()
    A.eq(item.file, "id:136235")
    A.same(snap.assets[item.file], { kind = "fileID", fileID = 136235 })
    texture:SetAtlas("Tooltip-Glow")
    item, snap = read()
    A.eq(item.atlas, "atlas:tooltip-glow")
    A.same(snap.assets[item.atlas], { kind = "atlas", atlas = "Tooltip-Glow" })
  end)
end

local function test_texture_look_fields()
  withTexture(function(_, texture, read)
    texture:SetColorTexture(1, 0, 0, 0.5)
    A.same(read().color, { 1, 0, 0, 0.5 })
    texture:SetColorTexture(0, 1, 0)
    A.same(read().color, { 0, 1, 0, 1 })
    texture:SetTexCoord(0, 0.5, 0, 1) -- W4: left, right, top, bottom -> UL, LL, UR, LR
    A.same(read().texCoord, { 0, 0, 0, 1, 0.5, 0, 0.5, 1 })
    texture:SetTexCoord(0, 0, 0, 1, 1, 0, 1, 1) -- the full image is the default, so nothing is exported
    A.eq(read().texCoord, nil)
    texture:SetVertexColor(1, 0.5, 0.25)
    A.same(read().vertexColor, { 1, 0.5, 0.25, 1 })
    local gradient = { orientation = "HORIZONTAL", min = { 1, 0, 0, 1 }, max = { 0, 0, 1, 1 } }
    texture:SetGradient("HORIZONTAL", { r = 1, g = 0, b = 0, a = 1 }, { r = 0, g = 0, b = 1, a = 1 })
    A.same(read().gradient, gradient)
    texture:SetBlendMode("ADD")
    texture:SetDesaturated(true)
    texture:SetRotation(1.5)
    texture:SetHorizTile(true)
    local item = read()
    A.eq(item.blendMode, "ADD")
    A.eq(item.desaturated, true)
    A.eq(item.rotation, 1.5)
    A.eq(item.horizTile, true)
    A.eq(item.vertTile, nil)
  end)
end

local function test_font_string_fields()
  withFontString(function(_, fontString, read)
    fontString:SetFont(FONT, 14, "OUTLINE")
    fontString:SetText("Hello")
    fontString:SetTextColor(1, 0.5, 0)
    fontString:SetJustifyH("LEFT")
    fontString:SetJustifyV("TOP")
    fontString:SetShadowOffset(1, -1)
    fontString:SetShadowColor(0, 0, 0, 0.75)
    fontString:SetWordWrap(false)
    fontString:SetMaxLines(2)
    fontString:SetSpacing(3)
    local item, snap = read()
    A.eq(item.text, "Hello")
    A.eq(item.font, "font:fonts/frizqt__.ttf")
    A.eq(item.size, 14)
    A.eq(item.flags, "OUTLINE")
    A.same(item.color, { 1, 0.5, 0, 1 })
    A.eq(item.justifyH, "LEFT")
    A.eq(item.justifyV, "TOP")
    A.same(item.shadow, { color = { 0, 0, 0, 0.75 }, x = 1, y = -1 })
    A.eq(item.wrap, false)
    A.eq(item.maxLines, 2)
    A.eq(item.spacing, 3)
    A.eq(snap.assets["font:fonts/frizqt__.ttf"].kind, "font")
  end)
end

local function test_fresh_font_string_defaults_assumed() -- (V11)
  withFontString(function(_, fontString, read)
    fontString:SetFont(FONT, 12, "")
    local item = read()
    A.eq(item.justifyH, "CENTER")
    A.eq(item.justifyV, "MIDDLE")
    A.eq(item.wrap, true)
    A.eq(item.maxLines, 0)
    A.eq(item.spacing, 0)
    A.eq(item.shadow, nil)
    A.same(item.color, { 1, 1, 1, 1 })
  end)
end

local function test_font_string_without_a_set_width_is_auto_width()
  withFontString(function(_, fontString, read)
    fontString:SetFont(FONT, 12, "")
    fontString:SetText("Hello")
    A.eq(read().autoWidth, true)
  end)
end

local function test_font_string_with_a_set_width_is_not_auto_width()
  withFontString(function(_, fontString, read)
    fontString:SetFont(FONT, 12, "")
    fontString:SetText("Hello")
    fontString:SetWidth(100)
    A.eq(read().autoWidth, nil)
  end)
end

local function test_font_string_stretched_between_anchors_is_not_auto_width()
  withFontString(function(_, fontString, read)
    fontString:SetFont(FONT, 12, "")
    fontString:SetText("Hello")
    fontString:ClearAllPoints()
    fontString:SetPoint("LEFT")
    fontString:SetPoint("RIGHT")
    A.eq(read().autoWidth, nil)
  end)
end

local function test_font_string_escapes_register_assets()
  withFontString(function(_, fontString, read)
    fontString:SetFont(FONT, 12, "")
    fontString:SetText("|TInterface\\Icons\\Foo:16|t |A:bar-atlas:16:16|a")
    local _, snap = read()
    A.same(snap.assets["path:interface/icons/foo"], { kind = "path", path = "Interface/Icons/Foo" })
    A.same(snap.assets["atlas:bar-atlas"], { kind = "atlas", atlas = "bar-atlas" })
  end)
end

return function()
  test_texture_file_refs_and_assets()
  test_texture_look_fields()
  test_font_string_fields()
  test_fresh_font_string_defaults_assumed()
  test_font_string_without_a_set_width_is_auto_width()
  test_font_string_with_a_set_width_is_not_auto_width()
  test_font_string_stretched_between_anchors_is_not_auto_width()
  test_font_string_escapes_register_assets()
end
